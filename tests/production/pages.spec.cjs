const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
test('deployed calculator displays the release and works online and offline', async ({ page, context }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const response = await page.goto('./');
  expect(response.status()).toBe(200);
  await expect(page.locator('#appVersion')).toContainText('v0.1.1');
  await expect(page.locator('#wt')).toHaveValue('');
  await page.locator('#wt').fill('60'); await page.locator('#ht').fill('170');
  await expect(page.locator('#rateOut')).toHaveText('10 mL/hr');
  await page.locator('[data-tab="asm"]').click();
  await expect(page.locator('#asmLoadOut')).toHaveText('3600 mg');
  await page.locator('#asmDrug').selectOption('fpht');
  await expect(page.locator('#asmDoseOut')).toHaveText('20 mg PE/kg');
  await page.locator('[data-tab="scores"]').click();
  await page.locator('#stessAge').check(); await page.locator('#stessNoHx').check();
  await page.locator('#stessType').selectOption('2'); await page.locator('#stessCon').selectOption('1');
  await expect(page.locator('#stessOut')).toHaveText('6/6');
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await context.setOffline(true); await page.goto('./privacy.html');
  await expect(page.locator('h1')).toHaveText('개인정보 처리방침');
  await page.goto('./index.html');
  await page.locator('#wt').fill('60'); await page.locator('#ht').fill('170');
  await expect(page.locator('#rateOut')).toHaveText('10 mL/hr');
  await page.locator('#mixMl').fill('0'); await expect(page.locator('#rateOut')).toHaveText('—');
  await page.locator('#mixMl').fill('500');
  await page.screenshot({ path: 'artifacts/deployed-web-phone.png', fullPage: true });
  expect(errors).toEqual([]);
  fs.writeFileSync('artifacts/deployed-web-browser.json', JSON.stringify({ url: page.url(), version: await page.locator('#appVersion').textContent(), checks: ['infusion 10 mL/hr', 'ASM 3600 mg', 'mg PE units', 'STESS 6/6', 'offline navigation', 'invalid input clears result'], pageErrors: errors, clinicalApproval: false }, null, 2) + '\n');
  console.log('Deployed browser checks passed: version, calculations, STESS, invalid input and offline navigation.');
});
